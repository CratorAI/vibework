/**
 * Bundle the slides core (parser, renderer, themes, PowerPoint builder with
 * pptxgenjs) into the skill folder, so the agent's export script runs with
 * vibework-js (the Bun built into the engine) and no package install.
 *
 * Run after changing anything in ./core:
 *   bun src/components/artifacts/slides/build-skill-core.ts
 * The test "skill bundle is up to date" fails when this was forgotten.
 */
import path from "node:path";
import { fileURLToPath } from "node:url";

// Bun-only script; the app's tsconfig has no Bun types
declare const Bun: any;

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../../../.vibework/skills/vibework-slides/scripts");

const result = await Bun.build({
  entrypoints: [path.join(here, "core/index.ts")],
  target: "bun",
  format: "esm",
  minify: true,
  naming: "deckCore.js",
  outdir: out,
});
if (!result.success) {
  for (const m of result.logs as unknown[]) console.error(m);
  process.exit(1);
}
const file = Bun.file(path.join(out, "deckCore.js"));
const header =
  "// Generated by src/components/artifacts/slides/build-skill-core.ts. Do not edit.\n" +
  "// Includes pptxgenjs (MIT), JSZip (MIT), image-size (MIT); see THIRD_PARTY_LICENSES.txt.\n";
await Bun.write(file, header + (await file.text()));
console.log(`wrote ${path.join(out, "deckCore.js")} (${Math.round(file.size / 1024)} KB)`);
